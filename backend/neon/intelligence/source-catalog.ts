export type CountrySourceCoverageInput = {
  code: string;
  name: string;
  region: string;
};

export function getCountrySourceCoverage(
  countries: readonly CountrySourceCoverageInput[],
) {
  return countries.map((country) => {
    const candidates = sourceCatalog.filter((source) =>
      source.countryCodes.includes(country.code),
    );
    return {
      ...country,
      candidateSourceCount: candidates.length,
      candidates,
      status: candidates.length > 0 ? "candidate_research_only" : "not_researched",
    } as const;
  });
}

export function getSourceCoverageSummary() {
  const liveRetrievedSources = sourceCatalog.filter(
    (source) => source.lastSuccessfulRetrieval !== null,
  );
  return {
    sourceProducts: sourceCatalog.length,
    countryCandidateReferences: sourceCatalog.reduce(
      (total, source) => total + source.countryCodes.length,
      0,
    ),
    countriesWithCandidates: new Set(
      sourceCatalog.flatMap((source) => source.countryCodes),
    ).size,
    liveRetrievedSources: liveRetrievedSources.length,
    retrievedSamplesWithKnownCount: liveRetrievedSources.reduce(
      (total, source) => total + (source.retrievedSampleCount ?? 0),
      0,
    ),
    parsedSamples: sourceCatalog.reduce(
      (total, source) => total + source.parsedSampleCount,
      0,
    ),
    storedRecords: sourceCatalog.reduce(
      (total, source) => total + source.storedRecordCount,
      0,
    ),
    permissionClearedSources: sourceCatalog.filter(
      (source) => source.stage === "operational",
    ).length,
    operationalConnectors: sourceCatalog.filter(
      (source) => source.stage === "operational" && source.connector !== "none",
    ).length,
  };
}
