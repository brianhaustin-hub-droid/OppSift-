export function getPlaylistClips(playlistIds: CinematicPlaylistId[]): CinematicVideoAsset[] {
  const idSet = new Set(playlistIds);
  const matching = CINEMATIC_MEDIA_MANIFEST.filter((clip) => idSet.has(clip.playlistId) && clip.status === 'Approved');
  return matching.length > 0 ? matching : CINEMATIC_MEDIA_MANIFEST.slice(0, 3);
}

export function getMediaCountsSummary() {
  const providers = Array.from(new Set(CINEMATIC_MEDIA_MANIFEST.map((c) => c.provider)));
  const licenses = Array.from(new Set(CINEMATIC_MEDIA_MANIFEST.map((c) => c.licenseName)));
  const approvedCount = CINEMATIC_MEDIA_MANIFEST.filter((c) => c.status === 'Approved' && c.commercialVerified && c.embedVerified).length;
  return {
    totalClips: CINEMATIC_MEDIA_MANIFEST.length,
    approvedCount,
    playlistCount: Object.keys(CINEMATIC_PLAYLISTS).length,
    providers,
    licenses,
  };
}
