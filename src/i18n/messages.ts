const catalogues: Record<LocaleCode, PartialMessages> = { en, pt, es, fr, ar };

export function translate(locale: LocaleCode, key: MessageKey): string {
  const catalogue = catalogues[locale] ?? catalogues.en;
  return catalogue[key] ?? en[key];
}

export function messageKeys(): MessageKey[] {
  return Object.keys(en) as MessageKey[];
}

export function localeCoverage(locale: LocaleCode): number {
  const catalogue = catalogues[locale] ?? {};
  return messageKeys().filter((key) => Boolean(catalogue[key])).length / messageKeys().length;
}

export const supportedLocaleCount = locales.length;
